-- T030: real treatment plans with patient acceptance and item-level execution.
-- Plans are clinical proposals; they do not by themselves create bills or prove treatment was performed.
CREATE TABLE treatment_plan (
    plan_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    patient_id bigint NOT NULL,
    branch_id bigint NOT NULL,
    dentist_id bigint NOT NULL,
    source_visit_id bigint NOT NULL,
    title varchar(120) NOT NULL,
    diagnosis text,
    state varchar(20) NOT NULL,
    estimated_total_cents bigint NOT NULL DEFAULT 0,
    version integer NOT NULL DEFAULT 1,
    created_by bigint NOT NULL,
    created_at timestamptz NOT NULL,
    accepted_at timestamptz,
    acceptance_basis varchar(300),
    rejected_reason varchar(300),
    CONSTRAINT pk_treatment_plan PRIMARY KEY (plan_id),
    CONSTRAINT ck_treatment_plan_total CHECK (estimated_total_cents >= 0),
    CONSTRAINT ck_treatment_plan_version CHECK (version > 0),
    CONSTRAINT ck_treatment_plan_state CHECK (state IN ('草稿','待患者确认','已接受','已拒绝','已终止','已完成')),
    CONSTRAINT ck_treatment_plan_acceptance CHECK (
        (state IN ('已接受','已完成') AND accepted_at IS NOT NULL AND acceptance_basis IS NOT NULL)
        OR (state NOT IN ('已接受','已完成'))
    ),
    CONSTRAINT fk_treatment_plan_patient FOREIGN KEY (patient_id) REFERENCES patient(patient_id) ON DELETE RESTRICT,
    CONSTRAINT fk_treatment_plan_branch FOREIGN KEY (branch_id) REFERENCES branch(branch_id) ON DELETE RESTRICT,
    CONSTRAINT fk_treatment_plan_dentist FOREIGN KEY (dentist_id) REFERENCES staff(staff_id) ON DELETE RESTRICT,
    CONSTRAINT fk_treatment_plan_visit FOREIGN KEY (source_visit_id) REFERENCES visit_record(visit_id) ON DELETE RESTRICT
);
COMMENT ON TABLE treatment_plan IS '治疗计划主单，患者接受后才可作为执行依据';

CREATE TABLE treatment_plan_item (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    plan_id bigint NOT NULL,
    service_item_id bigint,
    name varchar(100) NOT NULL,
    tooth_position varchar(20),
    phase varchar(40),
    quantity integer NOT NULL DEFAULT 1,
    unit_price_cents bigint NOT NULL,
    amount_cents bigint NOT NULL,
    status varchar(20) NOT NULL DEFAULT '计划',
    sort_order integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_treatment_plan_item PRIMARY KEY (item_id),
    CONSTRAINT ck_treatment_plan_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_treatment_plan_item_amount CHECK (unit_price_cents >= 0 AND amount_cents >= 0),
    CONSTRAINT ck_treatment_plan_item_status CHECK (status IN ('计划','进行中','已完成','已取消')),
    CONSTRAINT fk_treatment_plan_item_plan FOREIGN KEY (plan_id) REFERENCES treatment_plan(plan_id) ON DELETE CASCADE,
    CONSTRAINT fk_treatment_plan_item_service FOREIGN KEY (service_item_id) REFERENCES service_item(item_id) ON DELETE RESTRICT
);
COMMENT ON TABLE treatment_plan_item IS '治疗计划项目明细，金额为整数分，不代表已收费';
