-- T025-B1: first credential review and append-only review history.
-- No backfill: history starts at this migration; existing rows keep their current facts.
ALTER TABLE credential ADD COLUMN version integer NOT NULL DEFAULT 1;
ALTER TABLE credential ADD CONSTRAINT ck_credential_version CHECK (version > 0);
COMMENT ON COLUMN credential.version IS '资格并发版本，默认1';

CREATE TABLE credential_review (
    review_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    credential_id bigint NOT NULL,
    action varchar(20) NOT NULL,
    from_state varchar(20),
    to_state varchar(20) NOT NULL,
    actor_staff_id bigint NOT NULL,
    basis varchar(300),
    occurred_at timestamptz NOT NULL,
    resulting_version integer NOT NULL,
    CONSTRAINT pk_credential_review PRIMARY KEY (review_id),
    CONSTRAINT ck_credential_review_action CHECK (action IN ('submit','verify','reject')),
    CONSTRAINT ck_credential_review_from_state CHECK (from_state IS NULL OR from_state IN ('pending','verified','rejected')),
    CONSTRAINT ck_credential_review_to_state CHECK (to_state IN ('pending','verified','rejected')),
    CONSTRAINT ck_credential_review_transition CHECK (
        (action='submit' AND from_state IS NULL AND to_state='pending') OR
        (action='verify' AND from_state='pending' AND to_state='verified') OR
        (action='reject' AND from_state='pending' AND to_state='rejected')
    ),
    CONSTRAINT ck_credential_review_basis CHECK (
        action='submit' OR (basis IS NOT NULL AND btrim(basis)<>'')
    ),
    CONSTRAINT ck_credential_review_version CHECK (resulting_version > 0)
);
COMMENT ON COLUMN credential_review.review_id IS '审核记录编号';
COMMENT ON COLUMN credential_review.credential_id IS '资格记录';
COMMENT ON COLUMN credential_review.action IS 'submit、verify或reject';
COMMENT ON COLUMN credential_review.from_state IS '变更前状态；submit为空';
COMMENT ON COLUMN credential_review.to_state IS '变更后状态';
COMMENT ON COLUMN credential_review.actor_staff_id IS '执行人';
COMMENT ON COLUMN credential_review.basis IS '审核依据；submit可为空';
COMMENT ON COLUMN credential_review.occurred_at IS '服务端时间';
COMMENT ON COLUMN credential_review.resulting_version IS '本次变更后的credential.version';

ALTER TABLE credential_review ADD CONSTRAINT fk_credential_review_credential_id
    FOREIGN KEY (credential_id) REFERENCES credential (credential_id) ON DELETE RESTRICT;
ALTER TABLE credential_review ADD CONSTRAINT fk_credential_review_actor_staff_id
    FOREIGN KEY (actor_staff_id) REFERENCES staff (staff_id) ON DELETE RESTRICT;
CREATE INDEX ix_credential_review_credential_id ON credential_review(credential_id, review_id);
CREATE INDEX ix_credential_review_actor_staff_id ON credential_review(actor_staff_id);
