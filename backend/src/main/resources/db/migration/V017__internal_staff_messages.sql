-- Branch-scoped, immutable staff conversation. Messages never change appointments or clinical records.
CREATE TABLE internal_staff_message (
    message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id bigint NOT NULL REFERENCES branch(branch_id) ON DELETE RESTRICT,
    frontdesk_staff_id bigint NOT NULL REFERENCES staff(staff_id) ON DELETE RESTRICT,
    dentist_staff_id bigint NOT NULL REFERENCES staff(staff_id) ON DELETE RESTRICT,
    sender_account_id bigint NOT NULL REFERENCES account(account_id) ON DELETE RESTRICT,
    body varchar(500) NOT NULL,
    sent_at timestamptz NOT NULL,
    CONSTRAINT ck_internal_message_distinct_staff CHECK (frontdesk_staff_id <> dentist_staff_id),
    CONSTRAINT ck_internal_message_body CHECK (length(btrim(body)) BETWEEN 1 AND 500)
);
CREATE INDEX ix_internal_message_thread ON internal_staff_message
    (branch_id, frontdesk_staff_id, dentist_staff_id, message_id DESC);
COMMENT ON TABLE internal_staff_message IS '前台与医生门店内沟通；不可编辑删除，不触发预约或诊疗状态变更';
COMMENT ON COLUMN internal_staff_message.body IS '内部工作消息；禁止在界面引导填写证件号或完整病历';

INSERT INTO permission(code,name) VALUES ('messages.exchange','本店前台与医生内部沟通')
ON CONFLICT (code) DO NOTHING;
INSERT INTO role_permission(role_id,permission_id)
SELECT r.role_id,p.permission_id FROM role r CROSS JOIN permission p
WHERE r.code IN ('frontdesk','dentist') AND p.code='messages.exchange'
ON CONFLICT DO NOTHING;
