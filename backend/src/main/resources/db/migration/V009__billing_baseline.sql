-- T029: real billing records for offline clinic collection, refunds and manual invoices.
-- No payment gateway or formal e-invoice integration is implied by these tables.
CREATE TABLE bill (
    bill_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    patient_id bigint NOT NULL,
    branch_id bigint NOT NULL,
    visit_id bigint,
    appointment_id bigint,
    total_cents bigint NOT NULL,
    paid_cents bigint NOT NULL DEFAULT 0,
    status varchar(20) NOT NULL,
    version integer NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL,
    CONSTRAINT pk_bill PRIMARY KEY (bill_id),
    CONSTRAINT ck_bill_total CHECK (total_cents >= 0),
    CONSTRAINT ck_bill_paid CHECK (paid_cents >= 0 AND paid_cents <= total_cents),
    CONSTRAINT ck_bill_version CHECK (version > 0),
    CONSTRAINT ck_bill_status CHECK (status IN ('待收款','部分收款','已收款','部分退款','已退款','已取消')),
    CONSTRAINT fk_bill_patient FOREIGN KEY (patient_id) REFERENCES patient(patient_id) ON DELETE RESTRICT,
    CONSTRAINT fk_bill_branch FOREIGN KEY (branch_id) REFERENCES branch(branch_id) ON DELETE RESTRICT,
    CONSTRAINT fk_bill_visit FOREIGN KEY (visit_id) REFERENCES visit_record(visit_id) ON DELETE RESTRICT,
    CONSTRAINT fk_bill_appointment FOREIGN KEY (appointment_id) REFERENCES appointment(appointment_id) ON DELETE RESTRICT
);
COMMENT ON TABLE bill IS '线下收费账单，不等同于支付渠道流水';
COMMENT ON COLUMN bill.total_cents IS '应收总额，整数分';

CREATE TABLE bill_item (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    bill_id bigint NOT NULL,
    name varchar(100) NOT NULL,
    quantity integer NOT NULL,
    unit_price_cents bigint NOT NULL,
    amount_cents bigint NOT NULL,
    CONSTRAINT pk_bill_item PRIMARY KEY (item_id),
    CONSTRAINT ck_bill_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_bill_item_prices CHECK (unit_price_cents >= 0 AND amount_cents >= 0),
    CONSTRAINT fk_bill_item_bill FOREIGN KEY (bill_id) REFERENCES bill(bill_id) ON DELETE CASCADE
);
COMMENT ON TABLE bill_item IS '账单明细，金额为整数分';

CREATE TABLE payment (
    payment_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    bill_id bigint NOT NULL,
    amount_cents bigint NOT NULL,
    method varchar(20) NOT NULL,
    state varchar(20) NOT NULL,
    received_by bigint NOT NULL,
    received_at timestamptz NOT NULL,
    note varchar(300),
    CONSTRAINT pk_payment PRIMARY KEY (payment_id),
    CONSTRAINT ck_payment_amount CHECK (amount_cents > 0),
    CONSTRAINT ck_payment_method CHECK (method IN ('现金','银行卡','微信线下登记','其他线下')),
    CONSTRAINT ck_payment_state CHECK (state IN ('已登记','已退款')),
    CONSTRAINT fk_payment_bill FOREIGN KEY (bill_id) REFERENCES bill(bill_id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_staff FOREIGN KEY (received_by) REFERENCES staff(staff_id) ON DELETE RESTRICT
);
COMMENT ON TABLE payment IS '受控线下收款登记，不表示已调用支付渠道';

CREATE TABLE refund (
    refund_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    bill_id bigint NOT NULL,
    payment_id bigint,
    amount_cents bigint NOT NULL,
    reason varchar(300) NOT NULL,
    status varchar(20) NOT NULL,
    requested_by bigint NOT NULL,
    requested_at timestamptz NOT NULL,
    processed_at timestamptz,
    processed_by bigint,
    CONSTRAINT pk_refund PRIMARY KEY (refund_id),
    CONSTRAINT ck_refund_amount CHECK (amount_cents > 0),
    CONSTRAINT ck_refund_status CHECK (status IN ('待处理','已退款','已拒绝')),
    CONSTRAINT fk_refund_bill FOREIGN KEY (bill_id) REFERENCES bill(bill_id) ON DELETE RESTRICT,
    CONSTRAINT fk_refund_payment FOREIGN KEY (payment_id) REFERENCES payment(payment_id) ON DELETE RESTRICT
);
COMMENT ON TABLE refund IS '线下退款登记，不代表支付渠道原路退回';

CREATE TABLE invoice (
    invoice_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    bill_id bigint NOT NULL,
    title varchar(120) NOT NULL,
    amount_cents bigint NOT NULL,
    status varchar(20) NOT NULL,
    requested_by bigint NOT NULL,
    requested_at timestamptz NOT NULL,
    issued_at timestamptz,
    issued_by bigint,
    note varchar(300),
    CONSTRAINT pk_invoice PRIMARY KEY (invoice_id),
    CONSTRAINT ck_invoice_amount CHECK (amount_cents > 0),
    CONSTRAINT ck_invoice_status CHECK (status IN ('待开票','已开票','已拒绝')),
    CONSTRAINT fk_invoice_bill FOREIGN KEY (bill_id) REFERENCES bill(bill_id) ON DELETE RESTRICT
);
COMMENT ON TABLE invoice IS '人工票据处理记录，不是税控正式发票';
