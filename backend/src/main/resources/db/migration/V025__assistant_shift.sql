CREATE TABLE assistant_shift (
    shift_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id bigint NOT NULL REFERENCES staff(staff_id) ON DELETE RESTRICT,
    branch_id bigint NOT NULL REFERENCES branch(branch_id) ON DELETE RESTRICT,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    state varchar(20) NOT NULL DEFAULT '已排班',
    version integer NOT NULL DEFAULT 1,
    CONSTRAINT ck_assistant_shift_interval CHECK (ends_at > starts_at),
    CONSTRAINT ck_assistant_shift_state CHECK (state IN ('已排班','已取消')),
    CONSTRAINT ck_assistant_shift_version CHECK (version > 0)
);

CREATE INDEX ix_assistant_shift_branch_time ON assistant_shift(branch_id,starts_at);
CREATE INDEX ix_assistant_shift_staff_time ON assistant_shift(staff_id,starts_at);
ALTER TABLE assistant_shift ADD CONSTRAINT ex_assistant_shift_overlap
  EXCLUDE USING gist (staff_id WITH =, tstzrange(starts_at,ends_at,'[)') WITH &&)
  WHERE (state='已排班');

COMMENT ON TABLE assistant_shift IS '门店诊疗助手班次；不产生牙医号源或预约资格';
