-- Ordinary consumable receiving baseline. No clinical issue, transfer, payment or tax posting.
CREATE TABLE stock_item (
    stock_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(40) NOT NULL UNIQUE,
    name varchar(120) NOT NULL,
    kind varchar(20) NOT NULL CHECK (kind IN ('药品','耗材')),
    specification varchar(120) NOT NULL,
    base_unit varchar(20) NOT NULL,
    approval_no varchar(80),
    storage_condition varchar(200) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_stock_item_text CHECK (length(btrim(code))>0 AND length(btrim(name))>0
        AND length(btrim(specification))>0 AND length(btrim(base_unit))>0 AND length(btrim(storage_condition))>0)
);

CREATE TABLE stock_batch (
    batch_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id bigint NOT NULL REFERENCES stock_item(stock_item_id) ON DELETE RESTRICT,
    manufacturer varchar(120) NOT NULL,
    holder_name varchar(120),
    batch_no varchar(80) NOT NULL,
    expires_on date NOT NULL,
    trace_reference varchar(300),
    state varchar(20) NOT NULL CHECK (state IN ('合格','隔离','召回')),
    CONSTRAINT uq_stock_batch_business UNIQUE (stock_item_id,manufacturer,batch_no),
    CONSTRAINT ck_stock_batch_text CHECK (length(btrim(manufacturer))>0 AND length(btrim(batch_no))>0)
);

CREATE TABLE warehouse (
    warehouse_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id bigint NOT NULL REFERENCES branch(branch_id) ON DELETE RESTRICT,
    name varchar(80) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_warehouse_branch_name UNIQUE (branch_id,name),
    CONSTRAINT ck_warehouse_name CHECK (length(btrim(name))>0)
);
CREATE INDEX ix_warehouse_branch ON warehouse(branch_id,warehouse_id);

CREATE TABLE purchase_receipt (
    receipt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id bigint NOT NULL REFERENCES branch(branch_id) ON DELETE RESTRICT,
    supplier_id bigint NOT NULL REFERENCES supplier(supplier_id) ON DELETE RESTRICT,
    document_no varchar(80) NOT NULL UNIQUE,
    supplier_document varchar(100) NOT NULL,
    received_at timestamptz NOT NULL,
    accepted_by bigint NOT NULL REFERENCES staff(staff_id) ON DELETE RESTRICT,
    state varchar(20) NOT NULL CHECK (state IN ('草稿','已过账','作废')),
    request_key varchar(64) NOT NULL UNIQUE,
    CONSTRAINT ck_purchase_receipt_text CHECK (length(btrim(document_no))>0
        AND length(btrim(supplier_document))>0 AND length(btrim(request_key))>0)
);
CREATE INDEX ix_purchase_receipt_branch ON purchase_receipt(branch_id,receipt_id DESC);
CREATE INDEX ix_purchase_receipt_supplier ON purchase_receipt(supplier_id,receipt_id DESC);

CREATE TABLE purchase_receipt_line (
    receipt_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id bigint NOT NULL REFERENCES purchase_receipt(receipt_id) ON DELETE RESTRICT,
    line_no integer NOT NULL CHECK (line_no>0),
    batch_id bigint NOT NULL REFERENCES stock_batch(batch_id) ON DELETE RESTRICT,
    warehouse_id bigint NOT NULL REFERENCES warehouse(warehouse_id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity>0),
    unit_cost numeric(14,4) NOT NULL CHECK (unit_cost>0),
    CONSTRAINT uq_purchase_receipt_line_no UNIQUE (receipt_id,line_no),
    CONSTRAINT uq_purchase_receipt_line_warehouse UNIQUE (receipt_line_id,warehouse_id)
);
CREATE INDEX ix_purchase_receipt_line_batch ON purchase_receipt_line(batch_id,receipt_line_id);

CREATE TABLE stock_movement (
    movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_line_id bigint NOT NULL,
    warehouse_id bigint NOT NULL REFERENCES warehouse(warehouse_id) ON DELETE RESTRICT,
    care_id bigint,
    reverses_id bigint UNIQUE REFERENCES stock_movement(movement_id) ON DELETE RESTRICT,
    transfer_key varchar(64),
    kind varchar(30) NOT NULL CHECK (kind='采购入库'),
    quantity_delta numeric(14,3) NOT NULL CHECK (quantity_delta<>0),
    occurred_at timestamptz NOT NULL,
    posted_at timestamptz NOT NULL,
    operator_id bigint NOT NULL REFERENCES staff(staff_id) ON DELETE RESTRICT,
    approved_by bigint REFERENCES staff(staff_id) ON DELETE RESTRICT,
    evidence varchar(300) NOT NULL CHECK (length(btrim(evidence))>0),
    request_key varchar(64) NOT NULL UNIQUE CHECK (length(btrim(request_key))>0),
    CONSTRAINT fk_stock_movement_receipt_line_warehouse FOREIGN KEY (receipt_line_id,warehouse_id)
        REFERENCES purchase_receipt_line(receipt_line_id,warehouse_id) ON DELETE RESTRICT,
    CONSTRAINT ck_stock_movement_initial_shape CHECK (quantity_delta>0 AND care_id IS NULL
        AND reverses_id IS NULL AND transfer_key IS NULL AND approved_by IS NULL)
);
CREATE UNIQUE INDEX uq_stock_movement_receipt_inbound ON stock_movement(receipt_line_id) WHERE kind='采购入库';
CREATE INDEX ix_stock_movement_balance ON stock_movement(warehouse_id,receipt_line_id);

-- A line must belong to a warehouse in the receiving branch. Posted lines cannot be changed.
CREATE FUNCTION enforce_receipt_line_boundary() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE receipt_state varchar(20); old_receipt_state varchar(20); receipt_branch bigint; warehouse_branch bigint;
BEGIN
    IF TG_OP='DELETE' THEN
        SELECT state INTO receipt_state FROM purchase_receipt WHERE receipt_id=OLD.receipt_id;
        IF receipt_state IS DISTINCT FROM '草稿' THEN RAISE EXCEPTION 'final receipt line is immutable' USING ERRCODE='23514'; END IF;
        RETURN OLD;
    END IF;
    SELECT state,branch_id INTO receipt_state,receipt_branch FROM purchase_receipt WHERE receipt_id=NEW.receipt_id;
    SELECT branch_id INTO warehouse_branch FROM warehouse WHERE warehouse_id=NEW.warehouse_id;
    IF TG_OP='UPDATE' THEN
        SELECT state INTO old_receipt_state FROM purchase_receipt WHERE receipt_id=OLD.receipt_id;
        IF EXISTS (SELECT 1 FROM stock_movement WHERE receipt_line_id=OLD.receipt_line_id) THEN
            RAISE EXCEPTION 'receipt line with inbound movement is immutable' USING ERRCODE='23514';
        END IF;
    END IF;
    IF receipt_state IS DISTINCT FROM '草稿' OR (TG_OP='UPDATE' AND old_receipt_state IS DISTINCT FROM '草稿') THEN
        RAISE EXCEPTION 'final receipt line is immutable' USING ERRCODE='23514';
    END IF;
    IF receipt_branch IS DISTINCT FROM warehouse_branch THEN
        RAISE EXCEPTION 'receipt warehouse belongs to another branch' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tr_receipt_line_boundary BEFORE INSERT OR UPDATE OR DELETE ON purchase_receipt_line
    FOR EACH ROW EXECUTE FUNCTION enforce_receipt_line_boundary();

CREATE FUNCTION reject_posted_receipt_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE line_count integer; inbound_count integer; invalid_line_count integer;
BEGIN
    IF OLD.state IN ('已过账','作废') THEN RAISE EXCEPTION 'final receipt is immutable' USING ERRCODE='23514'; END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    IF NEW.state='已过账' THEN
        SELECT count(*),count(m.movement_id) INTO line_count,inbound_count
        FROM purchase_receipt_line l LEFT JOIN stock_movement m
          ON m.receipt_line_id=l.receipt_line_id AND m.kind='采购入库'
        WHERE l.receipt_id=NEW.receipt_id;
        IF line_count=0 OR line_count<>inbound_count THEN
            RAISE EXCEPTION 'posted receipt requires one inbound movement per line' USING ERRCODE='23514';
        END IF;
        SELECT count(*) INTO invalid_line_count
        FROM purchase_receipt_line l
        JOIN warehouse w ON w.warehouse_id=l.warehouse_id
        JOIN stock_movement m ON m.receipt_line_id=l.receipt_line_id AND m.kind='采购入库'
        WHERE l.receipt_id=NEW.receipt_id
          AND (w.branch_id<>NEW.branch_id OR m.quantity_delta<>l.quantity);
        IF invalid_line_count>0 THEN
            RAISE EXCEPTION 'posted receipt branch or quantity differs from inbound movement' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tr_posted_receipt_immutable BEFORE UPDATE OR DELETE ON purchase_receipt
    FOR EACH ROW EXECUTE FUNCTION reject_posted_receipt_change();

CREATE FUNCTION require_receipt_draft_insert() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.state<>'草稿' THEN RAISE EXCEPTION 'new receipt must be posted through draft transaction' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tr_receipt_draft_insert BEFORE INSERT ON purchase_receipt
    FOR EACH ROW EXECUTE FUNCTION require_receipt_draft_insert();

CREATE FUNCTION validate_inbound_movement() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE line_quantity numeric(14,3); receipt_state varchar(20);
BEGIN
    IF NEW.kind='采购入库' THEN
        SELECT l.quantity,r.state INTO line_quantity,receipt_state
        FROM purchase_receipt_line l JOIN purchase_receipt r ON r.receipt_id=l.receipt_id
        WHERE l.receipt_line_id=NEW.receipt_line_id;
        IF receipt_state IS DISTINCT FROM '草稿' OR NEW.quantity_delta IS DISTINCT FROM line_quantity THEN
            RAISE EXCEPTION 'inbound movement must match one draft receipt line' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tr_validate_inbound_movement BEFORE INSERT ON stock_movement
    FOR EACH ROW EXECUTE FUNCTION validate_inbound_movement();

CREATE FUNCTION reject_stock_movement_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'stock movement is append-only' USING ERRCODE='23514';
END $$;
CREATE TRIGGER tr_stock_movement_append_only BEFORE UPDATE OR DELETE ON stock_movement
    FOR EACH ROW EXECUTE FUNCTION reject_stock_movement_change();

CREATE FUNCTION protect_stock_master_facts() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME='warehouse' THEN
        IF NEW.branch_id IS DISTINCT FROM OLD.branch_id THEN
            RAISE EXCEPTION 'warehouse branch is immutable' USING ERRCODE='23514';
        END IF;
    ELSIF TG_TABLE_NAME='stock_batch' THEN
        IF (NEW.stock_item_id,NEW.manufacturer,NEW.holder_name,NEW.batch_no,NEW.expires_on,NEW.trace_reference)
            IS DISTINCT FROM (OLD.stock_item_id,OLD.manufacturer,OLD.holder_name,OLD.batch_no,OLD.expires_on,OLD.trace_reference)
            AND EXISTS (SELECT 1 FROM purchase_receipt_line l JOIN purchase_receipt r ON r.receipt_id=l.receipt_id
                WHERE l.batch_id=OLD.batch_id AND r.state='已过账') THEN
            RAISE EXCEPTION 'posted batch facts are immutable' USING ERRCODE='23514';
        END IF;
    ELSIF TG_TABLE_NAME='stock_item' THEN
        IF (NEW.kind,NEW.base_unit) IS DISTINCT FROM (OLD.kind,OLD.base_unit)
            AND EXISTS (SELECT 1 FROM stock_batch b JOIN purchase_receipt_line l ON l.batch_id=b.batch_id
                JOIN purchase_receipt r ON r.receipt_id=l.receipt_id
                WHERE b.stock_item_id=OLD.stock_item_id AND r.state='已过账') THEN
            RAISE EXCEPTION 'posted item unit and kind are immutable' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tr_warehouse_branch_immutable BEFORE UPDATE ON warehouse
    FOR EACH ROW EXECUTE FUNCTION protect_stock_master_facts();
CREATE TRIGGER tr_stock_batch_facts_immutable BEFORE UPDATE ON stock_batch
    FOR EACH ROW EXECUTE FUNCTION protect_stock_master_facts();
CREATE TRIGGER tr_stock_item_unit_immutable BEFORE UPDATE ON stock_item
    FOR EACH ROW EXECUTE FUNCTION protect_stock_master_facts();

