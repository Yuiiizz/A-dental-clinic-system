DECLARE invalid_ids text;
BEGIN
 SELECT string_agg(appointment_id::text, ',') INTO invalid_ids FROM (
  SELECT a.appointment_id FROM appointment a LEFT JOIN schedule s ON s.schedule_id=a.schedule_id
  WHERE a.state IN ('已确认','候诊中','接诊中','已完成','已改约')
  AND (s.schedule_id IS NULL OR a.branch_id<>s.branch_id OR a.confirmed_at IS NULL
       OR (a.confirmed_dentist_id IS NOT NULL AND a.confirmed_dentist_id<>s.dentist_id))
  ORDER BY a.appointment_id LIMIT 20
 ) invalid;
 IF invalid_ids IS NOT NULL THEN RAISE EXCEPTION 'Confirmation backfill rejected; appointment IDs: %', invalid_ids; END IF;
END $$;
